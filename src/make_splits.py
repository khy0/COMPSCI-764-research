"""Generate the frozen train/val/test split + nested training subsets.

Run EXACTLY ONCE, then commit the output files under data/splits/ — this script
must never be re-run as part of the training/eval pipeline (planning doc, P1: a
library version bump silently changing a shuffle would invalidate every result).

Reads dataset.n_images_total and the split/subset sizes from configs/data.yaml,
so the config is the single source of truth for split sizes; this script only
implements the (seeded, deterministic) sampling procedure:

  1. List all image IDs in data/kvasir-seg/images/ (stem, no extension), sorted
     alphabetically first (Python's os.listdir order is filesystem-dependent —
     sorting first is what makes step 2 reproducible across machines/OSes).
  2. Shuffle with np.random.RandomState(seed) (seed = dataset.seed in the config).
  3. Slice off test, then val, then the remainder is train_pool — in that order,
     so train_pool is always the same regardless of how many of the four nested
     subsets get used downstream.
  4. The four nested subsets are prefixes of the (already-shuffled) train_pool
     list, so train_10 ⊂ train_25 ⊂ train_50 ⊂ train_100 by construction (P2) —
     no separate sampling step, no risk of the subsets disagreeing with each other.

Usage
-----
    python src/make_splits.py --config configs/data.yaml

Fails loudly (does not silently proceed) if:
  - data/kvasir-seg/images/ does not exist or contains a different image count
    than configs/data.yaml: dataset.n_images_total.
  - Any output split file already exists (use --force to intentionally
    regenerate — this should essentially never happen after Week 1; if it does,
    log why in decisions.md, since every result downstream is invalidated).
"""

from __future__ import annotations

import argparse
import os

import numpy as np
import yaml


def list_image_ids(images_dir: str, image_ext: str = ".jpg") -> list[str]:
    if not os.path.isdir(images_dir):
        raise FileNotFoundError(
            f"{images_dir} does not exist. Download and extract Kvasir-SEG there "
            f"first — see data/kvasir-seg/README.md."
        )
    ids = sorted(
        os.path.splitext(f)[0]
        for f in os.listdir(images_dir)
        if f.lower().endswith(image_ext)
    )
    return ids


def make_splits(config: dict, images_dir: str) -> dict[str, list[str]]:
    ds = config["dataset"]
    splits_cfg = config["splits"]
    nested_cfg = config["nested_subsets"]
    seed = ds["seed"]

    ids = list_image_ids(images_dir)
    if len(ids) != ds["n_images_total"]:
        raise ValueError(
            f"Found {len(ids)} images in {images_dir}, expected "
            f"{ds['n_images_total']} (configs/data.yaml: dataset.n_images_total). "
            f"Check the Kvasir-SEG download is complete before generating splits."
        )

    rng = np.random.RandomState(seed)
    shuffled = list(ids)
    rng.shuffle(shuffled)

    n_test = splits_cfg["test"]["n_images"]
    n_val = splits_cfg["val"]["n_images"]
    n_train_pool = splits_cfg["train_pool"]["n_images"]
    if n_test + n_val + n_train_pool != len(ids):
        raise ValueError(
            f"configs/data.yaml split sizes ({n_test} + {n_val} + {n_train_pool} "
            f"= {n_test + n_val + n_train_pool}) do not sum to n_images_total "
            f"({len(ids)})."
        )

    test_ids = shuffled[:n_test]
    val_ids = shuffled[n_test : n_test + n_val]
    train_pool_ids = shuffled[n_test + n_val : n_test + n_val + n_train_pool]

    out = {
        splits_cfg["test"]["file"]: test_ids,
        splits_cfg["val"]["file"]: val_ids,
        splits_cfg["train_pool"]["file"]: train_pool_ids,
    }

    for entry in nested_cfg:
        n = entry["n_images"]
        if n > len(train_pool_ids):
            raise ValueError(
                f"Nested subset {entry['file']} asks for {n} images but "
                f"train_pool only has {len(train_pool_ids)}."
            )
        # Prefix of the already-shuffled train_pool -> automatic nesting (P2).
        out[entry["file"]] = train_pool_ids[:n]

    return out


def write_split_files(splits: dict[str, list[str]], force: bool) -> None:
    for path, ids in splits.items():
        if os.path.exists(path) and not force:
            raise FileExistsError(
                f"{path} already exists. Frozen splits should not be regenerated "
                f"(planning doc, P1) — pass --force if this is an intentional, "
                f"logged exception (see decisions.md)."
            )
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(f"# Generated by src/make_splits.py — {len(ids)} images. Do not hand-edit.\n")
            for image_id in ids:
                f.write(image_id + "\n")
        print(f"Wrote {len(ids):4d} IDs -> {path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/data.yaml")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    with open(args.config) as f:
        config = yaml.safe_load(f)

    images_dir = os.path.join(config["dataset"]["path"], "images")
    splits = make_splits(config, images_dir)

    # Sanity check: no image ID appears in more than one of {test, val, train_pool}.
    test_ids = set(splits[config["splits"]["test"]["file"]])
    val_ids = set(splits[config["splits"]["val"]["file"]])
    pool_ids = set(splits[config["splits"]["train_pool"]["file"]])
    assert not (test_ids & val_ids), "test/val overlap!"
    assert not (test_ids & pool_ids), "test/train_pool overlap!"
    assert not (val_ids & pool_ids), "val/train_pool overlap!"

    # Sanity check: nested subsets are true prefixes of train_pool, in order.
    prev = None
    for entry in config["nested_subsets"]:
        ids = splits[entry["file"]]
        if prev is not None:
            assert set(prev).issubset(set(ids)), f"{entry['file']} does not nest its predecessor!"
        prev = ids

    write_split_files(splits, force=args.force)
    print("All splits written. Commit data/splits/*.txt and never regenerate them.")


if __name__ == "__main__":
    main()
